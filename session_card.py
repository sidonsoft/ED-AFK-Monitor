"""Optional PNG recap card for session history; Pillow only needed when rendering."""
from datetime import datetime, timezone
from pathlib import Path


def render_card(store, path, title="ED AFK Monitor"):
    """Render totals and the best runs to a shareable PNG; returns '' or an error string."""
    totals = store.totals()
    if not totals["runs"]:
        return "No saved sessions yet; they are recorded automatically when the monitor stops."
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        return "PNG cards need 'pip install pillow'"
    best = sorted((row for row in store.sessions(limit=10_000) if row["duration"] > 0),
                  key=lambda row: row["bounties"], reverse=True)[:5]

    def font(size):
        try:
            return ImageFont.load_default(size=size)
        except TypeError:  # Pillow < 10.1 uses the tiny built-in bitmap font
            return ImageFont.load_default()

    width, height = 1280, 720
    image = Image.new("RGB", (width, height), (13, 17, 23))
    draw = ImageDraw.Draw(image)
    seconds = int(totals["duration"])
    draw.text((60, 40), title, fill=(240, 165, 0), font=font(48))
    draw.text((60, 118), f"{totals['runs']} sessions farmed · "
              f"{seconds // 3600}h{(seconds % 3600) // 60:02d}m",
              fill=(230, 232, 235), font=font(30))
    columns = [(f"{totals['kills']:,}", "kills"),
               (f"{totals['kills_hour']:,}/h", "kills per hour"),
               (f"{totals['bounties']:,} cr", "bounty rewards"),
               (f"{totals['bounties_hour']:,} cr/h", "rewards per hour")]
    x = 60
    for value, label in columns:
        draw.text((x, 200), value, fill=(120, 200, 255), font=font(40))
        draw.text((x, 262), label, fill=(140, 150, 162), font=font(22))
        x += 305
    y = 360
    for row in best:
        started = datetime.fromtimestamp(row["started"], timezone.utc).strftime("%Y-%m-%d %H:%M")
        seconds = int(row["duration"])
        hours = max(row["duration"] / 3600, 1 / 3600)
        draw.text((60, y), f"{started} · {seconds // 3600}h{(seconds % 3600) // 60:02d}m"
                  f" · {row['kills']:,} kills · {row['bounties']:,} cr"
                  f" · {round(row['bounties'] / hours):,} cr/h",
                  fill=(212, 216, 222), font=font(26))
        y += 54
    draw.text((60, height - 72), "Generated by ED AFK Monitor · journal-based AFK farming analytics",
              fill=(112, 122, 132), font=font(20))
    try:
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        image.save(path)
    except OSError as failure:
        return f"Could not write {path}: {failure}"
    return ""
